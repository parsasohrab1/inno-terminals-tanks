export function setLang(lng: "fa" | "en") {
  localStorage.setItem("lang", lng);
  i18n.changeLanguage(lng);
  document.documentElement.lang = lng;
  document.documentElement.dir = lng === "fa" ? "rtl" : "ltr";
}

